#!/usr/bin/env python3
"""Checks the docs the way a reader meets them. Run by ctest (the `docs` test); standard library only.

  1. Every relative link in docs/ and the READMEs the site carries points at a file that exists,
     and every #anchor into a Markdown file names one of its headings.
  2. Every page under docs/ is reachable by links from docs/README.md: nothing is orphaned.
  3. Every public header under include/ is named in its module's reference page, so a new
     header cannot land undocumented.

    python3 tools/docs/check_links.py          # exit status 1 and a list on failure
"""

import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import repo_links  # noqa: E402

ROOT = repo_links.repo_root()
HOME = "docs/README.md"
MODULE_PAGES = {
    "core": "docs/reference/core.md",
    "graphics": "docs/reference/graphics.md",
    "utils": "docs/reference/utils.md",
    "data_structures": "docs/reference/data-structures.md",
    "runtime": "docs/reference/runtime.md",
    "net": "docs/reference/net.md",
}


def read(repo_path):
    with open(os.path.join(ROOT, repo_path), encoding="utf-8") as f:
        return f.read()


def slugs(markdown):
    """Heading anchors as MkDocs (toc) and GitHub make them; a link may use either."""
    found = set()
    in_fence = False
    for line in markdown.splitlines():
        if repo_links.FENCE.match(line):
            in_fence = not in_fence
            continue
        if in_fence:
            continue
        m = re.match(r"^#{1,6}\s+(.*?)\s*#*\s*$", line)
        if not m:
            continue
        text = re.sub(r"`|\*\*|__|\[([^\]]*)\]\([^)]*\)", lambda g: g.group(1) or "", m.group(1)).strip()
        lowered = text.lower()
        found.add(re.sub(r"[-\s]+", "-", re.sub(r"[^\w\s-]", "", lowered)).strip("-"))   # mkdocs
        found.add(re.sub(r"[^\w\- ]", "", lowered).replace(" ", "-"))                      # github
    for m in re.finditer(r'(?:id|name)="([^"]+)"', markdown):
        found.add(m.group(1))
    return found


def docs_pages():
    pages = []
    for directory, dirs, names in os.walk(os.path.join(ROOT, "docs")):
        dirs[:] = sorted(d for d in dirs if d not in ("api",))
        for name in sorted(names):
            if name.endswith(".md"):
                pages.append(os.path.relpath(os.path.join(directory, name), ROOT).replace(os.sep, "/"))
    return pages


def main():
    problems = []
    pages = docs_pages() + repo_links.extra_pages(ROOT)
    page_set = set(pages)
    anchors = {}
    edges = {}

    for page in pages:
        text = read(page)
        edges[page] = set()
        for line, target in repo_links.iter_links(text):
            if repo_links.is_external(target):
                if target.startswith("#") and len(target) > 1:
                    anchors.setdefault(page, slugs(text))
                    if target[1:] not in anchors[page]:
                        problems.append(f"{page}:{line}: no heading for anchor {target}")
                continue
            resolved = repo_links.resolve(page, target)
            if resolved is None:
                problems.append(f"{page}:{line}: link leaves the repository: {target}")
                continue
            if resolved.startswith("docs/api"):
                continue   # generated by Doxygen
            absolute = os.path.join(ROOT, resolved)
            if not os.path.exists(absolute):
                problems.append(f"{page}:{line}: broken link: {target}")
                continue
            if os.path.isdir(absolute) and os.path.isfile(os.path.join(absolute, "README.md")):
                resolved = resolved.rstrip("/") + "/README.md"
            if resolved in page_set:
                edges[page].add(resolved)
            _, anchor = repo_links.split_target(target)
            if anchor and resolved.endswith(".md"):
                anchors.setdefault(resolved, slugs(read(resolved)))
                if anchor[1:] not in anchors[resolved]:
                    problems.append(f"{page}:{line}: no heading for anchor {anchor} in {resolved}")

    reached, frontier = {HOME}, [HOME]
    while frontier:
        for nxt in edges.get(frontier.pop(), ()):
            if nxt not in reached:
                reached.add(nxt)
                frontier.append(nxt)
    for page in docs_pages():
        if page not in reached:
            problems.append(f"{page}: not reachable by links from {HOME}")

    for module, page in MODULE_PAGES.items():
        text = read(page) if os.path.isfile(os.path.join(ROOT, page)) else ""
        folder = os.path.join(ROOT, "include", module)
        for directory, _, names in os.walk(folder):
            for name in sorted(names):
                if name.endswith(".h"):
                    header = os.path.relpath(os.path.join(directory, name), os.path.join(ROOT, "include"))
                    header = header.replace(os.sep, "/")
                    if header not in text:
                        problems.append(f"{page}: does not mention include/{header}")

    for problem in problems:
        print(problem)
    print(f"docs: {len(pages)} pages, {len(problems)} problem(s)")
    return 1 if problems else 0


if __name__ == "__main__":
    sys.exit(main())
